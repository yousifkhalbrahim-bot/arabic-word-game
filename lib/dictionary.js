// القاموس الأساسي له الأولوية: أي كلمة تشترك معه بنفس الحروف (بدون همزات) ما تنضاف،
// عشان قواعد الهمزة اللي فيه (أمام ≠ إمام) تبقى زي ما هي.
let _extendedCount = 0;
export const extendedCount = () => _extendedCount;

export function extendDictionary(words) {
  let added = 0;
  for (const raw of words) {
    const w = (raw || '').trim();
    if (!w) continue;
    const lk = normalize(w);
    const group = _looseMap.get(lk);
    if (group && group.some(x => _coreSet.has(x))) continue;
    const sk = normalizeStrict(w);
    if (!_strictMap.has(sk)) _strictMap.set(sk, w);
    if (!group) _looseMap.set(lk, [w]);
    else if (!group.includes(w)) group.push(w);
    NORMALIZED_DICT.add(lk);
    added++;
  }
  _extendedCount += added;
  return added;
}
